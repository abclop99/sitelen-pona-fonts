"""Geometric first drafts of each word, built from lines, circles and arcs.

make_templates.py puts these in the "drafts" layer of glyphs.svg. The build
uses a word's draft only while its page has nothing in the glyph or fill
layer, so drawing a word yourself replaces its draft. Drafts can also be
edited in place in Inkscape.

Coordinates are one page: 0-1000 with y down, ink box 100-900, centre
(500, 500). Paths are centrelines, stroked like the glyph layer.
"""

import math


def r(v):
    return f"{round(v, 1):g}"


def line(*pts):
    """Open polyline through (x, y) points."""
    return "M " + " L ".join(f"{r(x)},{r(y)}" for x, y in pts)


def closed(*pts):
    return line(*pts) + " Z"


def circle(cx, cy, rad):
    return ellipse(cx, cy, rad, rad)


KAPPA = 0.5523    # handle length, as a share of the radius, of a quarter ellipse


def ellipse(cx, cy, rx, ry, ends=KAPPA):
    """Four curves with nodes at the top, bottom and sides. ends > KAPPA
    lengthens the handles at the two ends of the long axis, which makes
    those ends blunter (less like an ellipse)."""
    kx = ky = KAPPA
    if rx >= ry:
        ky = ends      # handles at the left and right nodes run vertically
    else:
        kx = ends      # handles at the top and bottom nodes run horizontally
    hx, hy = rx * kx, ry * ky
    return (f"M {r(cx - rx)},{r(cy)} "
            f"C {r(cx - rx)},{r(cy + hy)} {r(cx - hx)},{r(cy + ry)} {r(cx)},{r(cy + ry)} "
            f"C {r(cx + hx)},{r(cy + ry)} {r(cx + rx)},{r(cy + hy)} {r(cx + rx)},{r(cy)} "
            f"C {r(cx + rx)},{r(cy - hy)} {r(cx + hx)},{r(cy - ry)} {r(cx)},{r(cy - ry)} "
            f"C {r(cx - hx)},{r(cy - ry)} {r(cx - rx)},{r(cy - hy)} {r(cx - rx)},{r(cy)} Z")


BLUNT = 0.64      # ends for eyes and sticks: slightly fuller than an ellipse


def dot(x, y, rad=8):
    # A tiny ring plus a point in its middle: stroked, they make a solid dot
    # 2 * rad + 40 wide (about 1.4 strokes at the default).
    return f"{circle(x, y, rad)} M {r(x)},{r(y)} h 0.1"


def big_dot(x, y):
    # The bigger dot: eyes and pupils stay small, places and mouths get this.
    return dot(x, y, 18)


def rect(x0, y0, x1, y1, rad=0):
    if not rad:
        return closed((x0, y0), (x1, y0), (x1, y1), (x0, y1))
    return (f"M {r(x0 + rad)},{r(y0)} H {r(x1 - rad)} A {rad},{rad} 0 0 1 {r(x1)},{r(y0 + rad)} "
            f"V {r(y1 - rad)} A {rad},{rad} 0 0 1 {r(x1 - rad)},{r(y1)} H {r(x0 + rad)} "
            f"A {rad},{rad} 0 0 1 {r(x0)},{r(y1 - rad)} V {r(y0 + rad)} "
            f"A {rad},{rad} 0 0 1 {r(x0 + rad)},{r(y0)} Z")


def spiral(cx, cy, step, turns):
    """Two-centre spiral from the middle outwards, one half turn per arc.

    Each arc's radius grows by step / 2, so the gap between rings is step.
    """
    x = cx + step / 2
    out = f"M {r(x)},{r(cy)}"
    for k in range(1, turns + 1):
        rad = step * k / 2
        x = x - 2 * rad if k % 2 else x + 2 * rad
        out += f" A {r(rad)},{r(rad)} 0 0 0 {r(x)},{r(cy)}"
    return out


def rays(y0=175, y1=300, spread=175, cx=500):
    """Three short lines fanning upwards, as on toki, sona, pana and kalama."""
    return " ".join([
        line((cx - spread, y0 + 50), (cx - spread * 0.55, y1)),
        line((cx, y0), (cx, y1)),
        line((cx + spread, y0 + 50), (cx + spread * 0.55, y1)),
    ])


def bowl(x0, x1, top, depth):
    """Flat top with a round bottom (uta, loje, moku)."""
    cx = (x0 + x1) / 2
    k = depth * 0.55
    return (f"M {r(x0)},{r(top)} H {r(x1)} C {r(x1)},{r(top + k)} {r(cx + k)},{r(top + depth)} "
            f"{r(cx)},{r(top + depth)} C {r(cx - k)},{r(top + depth)} {r(x0)},{r(top + k)} {r(x0)},{r(top)} Z")


def open_bowl(x0, x1, top, depth):
    """A bowl with no lid: straight down, round at the bottom (epiku's mouth)."""
    cx, hw = (x0 + x1) / 2, (x1 - x0) / 2
    kx, ky = hw * KAPPA, depth * KAPPA
    return (f"M {r(x0)},{r(top)} C {r(x0)},{r(top + ky)} {r(cx - kx)},{r(top + depth)} {r(cx)},{r(top + depth)} "
            f"C {r(cx + kx)},{r(top + depth)} {r(x1)},{r(top + ky)} {r(x1)},{r(top)}")


def arm(x0, x1, top, bottom, hook=True):
    """The luka shape: a check mark rising into an arch."""
    cx = (x0 + x1) / 2
    w = (x1 - x0) / 2
    d = f"M {r(x0)},{r(top + w)} C {r(x0)},{r(top + w * 0.45)} {r(cx - w * 0.55)},{r(top)} {r(cx)},{r(top)} "
    d += f"C {r(cx + w * 0.55)},{r(top)} {r(x1)},{r(top + w * 0.45)} {r(x1)},{r(top + w)} V {r(bottom)}"
    stem = f"M {r(x0)},{r(top + w)} V {r(bottom)}"
    if hook:
        stem = f"M {r(x0 - 100)},{r(bottom - 175)} L {r(x0)},{r(bottom)} V {r(top + w)}"
    return d + " " + stem


def heart(cx, top, w, h):
    """Heart with its point at the bottom."""
    hw = w / 2
    return (f"M {r(cx)},{r(top + h * 0.25)} "
            f"C {r(cx - hw * 0.25)},{r(top - h * 0.05)} {r(cx - hw * 1.05)},{r(top - h * 0.05)} {r(cx - hw)},{r(top + h * 0.35)} "
            f"C {r(cx - hw * 0.95)},{r(top + h * 0.6)} {r(cx - hw * 0.3)},{r(top + h * 0.8)} {r(cx)},{r(top + h)} "
            f"C {r(cx + hw * 0.3)},{r(top + h * 0.8)} {r(cx + hw * 0.95)},{r(top + h * 0.6)} {r(cx + hw)},{r(top + h * 0.35)} "
            f"C {r(cx + hw * 1.05)},{r(top - h * 0.05)} {r(cx + hw * 0.25)},{r(top - h * 0.05)} {r(cx)},{r(top + h * 0.25)} Z")


def j(*parts):
    return " ".join(parts)


